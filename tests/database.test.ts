 await asUser(a);const before:any=(await db.query('select public.get_snapshot() as data')).rows[0];assert.equal(before.data.reports.length,1);assert.equal(before.data.reports[0].observations[0].review.value,'pending');
 report.dateReviewed=true;report.observations[0]!.value='13.7';await call('save_report',report);
