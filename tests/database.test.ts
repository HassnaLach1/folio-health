 await assert.rejects(()=>call('save_report',report),/changed/);
 const badReport={...report,revision:1,observations:[{...report.observations[0],review:{value:null,unit:'reviewed',range:'reviewed'}}]};
 await assert.rejects(()=>call('save_report',badReport),/Invalid observation/);
 report.revision=1;report.date='2026-10-09';await call('save_report',report);
