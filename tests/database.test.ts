 assert.equal((await db.query('select * from storage.objects')).rows.length,0);
 await db.exec('reset role');await db.exec('set role service_role');
 const j:any=(await db.query('select public.claim_job() as job')).rows[0];assert.ok(j.job);
 const report={...demoSnapshot().reports[0]!,documentId:did,dateReviewed:false,observations:demoSnapshot().reports[0]!.observations};
 await db.query('select public.complete_extraction($1,$2,$3,$4::jsonb,$5)',[j.job.id,j.job.lease_token,'original source',JSON.stringify([report]),'test']);
